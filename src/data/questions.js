export const SECTION_COUNT = sections.length

export function getSectionById(id) {
  return sections.find((section) => section.id === id) ?? null
}

export function getQuestionsBySection(sectionId) {
  return questions.filter((question) => question.section === sectionId)
}

export function isAnswered(question, responses) {
  if (question.type === 'matrix') {
    return question.items.every((item) => responses[item.id] != null && responses[item.id] !== '')
  }

  const value = responses[question.id]
  if (question.type === 'multi') {
    return Array.isArray(value) && value.length > 0
  }
  if (question.type === 'text') {
    return typeof value === 'string' && value.trim().length > 0
  }
  return value !== undefined && value !== null && value !== ''
}
